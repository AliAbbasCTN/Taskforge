import type { Readable } from 'node:stream';

/** Thrown by `StorageService.get` when no object exists under a key. */
export class StorageObjectNotFoundError extends Error {
  constructor(key: string) {
    super(`No stored object for key "${key}"`);
    this.name = 'StorageObjectNotFoundError';
  }
}

/** One stored object, as reported by `StorageService.listKeys`. */
export interface StoredObjectInfo {
  key: string;
  lastModified: Date;
}

/**
 * WHAT: The contract every file-storage backend fulfils. The rest of TaskForge
 * depends on THIS, never on the file system or on S3 directly.
 *
 * WHY an abstract class: this is the "Dependency Inversion" principle in
 * practice. `AttachmentsService` asks for a `StorageService` and neither knows
 * nor cares whether bytes land in a folder on a developer's laptop or in an S3
 * bucket. Which implementation NestJS hands out is decided in ONE place
 * (`createStorage`) from one environment variable, STORAGE_DRIVER. Tests hand
 * in a fake. Adding a third backend (Azure, GCS) means writing one class.
 * (An abstract class rather than an `interface` because NestJS needs a
 * runtime value to use as an injection token - interfaces vanish when
 * TypeScript compiles.)
 *
 * Keys are opaque strings generated by the server (see `buildStorageKey`);
 * implementations must treat them as untrusted anyway.
 */
export abstract class StorageService {
  /** Stores `data` under `key`, replacing anything already there. */
  abstract put(key: string, data: Buffer, contentType: string): Promise<void>;

  /** A stream of the object's bytes. Throws `StorageObjectNotFoundError`. */
  abstract get(key: string): Promise<Readable>;

  /** Removes the object. Deleting something that does not exist is NOT an error. */
  abstract delete(key: string): Promise<void>;

  /** Every object whose key starts with `prefix`, in no particular order. */
  abstract listKeys(prefix: string): AsyncIterable<StoredObjectInfo>;
}
