import { randomUUID } from 'node:crypto';
import { isAbsolute, relative, resolve, sep } from 'node:path';
import { STORAGE_KEY_PREFIX } from '../files.constants';

/**
 * WHAT: Builds the "storage key" - the server-generated address under which an
 * uploaded file is kept.
 *
 *   attachments/<organizationId>/<projectId>/<taskId>/<random-uuid>.<ext>
 *
 * WHY generated, not derived from the file name: the key is where bytes get
 * written. If it contained any part of the uploader's file name, a name like
 * "../../server.js" would be an attack on the file system. Here every segment
 * is a UUID the server produced or looked up itself, and the extension was
 * already checked against the allow-list - so there is nothing for an attacker
 * to influence. The random UUID also makes keys unguessable and means two
 * uploads of "report.pdf" can never overwrite each other.
 *
 * The organisation / project / task segments are for operators: in S3 or on
 * disk you can see (and, with a bucket policy, restrict) whose files are whose.
 * Access is NOT decided by the key - it is decided by the database row and the
 * request guards.
 */
export function buildStorageKey(parts: {
  organizationId: string;
  projectId: string;
  taskId: string;
  extension: string;
}): string {
  return `${STORAGE_KEY_PREFIX}${parts.organizationId}/${parts.projectId}/${parts.taskId}/${randomUUID()}.${parts.extension}`;
}

/**
 * Resolves a storage key to a path INSIDE `rootDir`, or throws.
 *
 * Defence in depth: keys are generated by `buildStorageKey` and never come from
 * a client, so a hostile key should be impossible. This check exists so that
 * if a bug ever lets one through, the worst outcome is an error - not a file
 * written or deleted outside the uploads folder ("path traversal").
 */
export function resolveInside(rootDir: string, key: string): string {
  if (
    key === '' ||
    key.includes('\0') ||
    key.includes('\\') ||
    isAbsolute(key)
  ) {
    throw new Error('Invalid storage key');
  }
  const root = resolve(rootDir);
  const target = resolve(root, key);
  const rel = relative(root, target);
  if (rel === '' || rel.startsWith('..') || isAbsolute(rel)) {
    throw new Error('Invalid storage key');
  }
  // `relative` can still let `..`-free but different-root paths through on
  // exotic platforms; this final prefix check closes that.
  if (!target.startsWith(root + sep)) {
    throw new Error('Invalid storage key');
  }
  return target;
}
